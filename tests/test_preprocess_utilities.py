def test_beam_hardening_family(golden):
    params = mtp.fit_beam_hardening_curve(golden["p_samples"], golden["bh_samples"],
                                          num_parameters=4)
    err_p = _rel_max(params, golden["bh_params"])
    curve = mtp.apply_beam_hardening_curve(golden["p_samples"], golden["bh_params"])
    err_c = _rel_max(curve, golden["bh_curve"])
    cheb, dom = mtp.fit_inverse_beam_hardening_curve(
        golden["bh_params"], vmin=float(golden["y_domain"][0]),
        vmax=float(golden["y_domain"][1]), degree=8)
    err_i = _rel_max(cheb, golden["cheb_coeffs"])
    inv = mtp.apply_inverse_beam_hardening_curve(
        np.clip(golden["bh_curve"], golden["y_domain"][0], golden["y_domain"][1]),
        golden["cheb_coeffs"], tuple(golden["y_domain"]), clip=True)
    err_v = _rel_max(inv, golden["bh_inverse"])
    print(f"beam hardening rel_max = {err_p:.2e} (fit), {err_c:.2e} (fwd), "
          f"{err_i:.2e} (inv fit), {err_v:.2e} (inv apply)")
    # The two FIT gates are looser than the two APPLY gates on purpose.  Both
    # frameworks' beam-hardening fits stop at the solver's evaluation cap
    # without converging (the fit warns), and a truncated iterative fit is
    # environment-sensitive at the 1e-7 class -- regenerating the goldens in a
    # different environment measured a 9.4e-8 shift.  Curve APPLICATION is a
    # deterministic polynomial evaluation and keeps the float64 gate.
    assert err_p < 1e-6 and err_c < 1e-12 and err_i < 1e-6 and err_v < 1e-12


@pytest.mark.skipif(not os.path.exists(_h5_path), reason="no mbirjax-written cone save golden")
def test_load_mbirjax_cone_save(golden):
    # Golden read of an mbirjax-written file: the two packages share the on-disk layout, and that
    # file carries the older format tag, which the loader still accepts.
    sino, cone_params, opt_params, weights = mtp.load_cone_preprocessing(_h5_path)
    assert np.allclose(sino, golden["sino_trans"], rtol=1e-6, atol=1e-7)
    assert cone_params['sinogram_shape'] == tuple(golden["sino_trans"].shape)
    assert opt_params['sharpness'] == 1.25 and opt_params['det_channel_offset'] == 0.75
    assert weights is not None and weights.shape == golden["sino_trans"].shape


def _write_cone_save(tmp_path, golden, name='pp.h5'):
    """Write a small cone-preprocessing file; return its path and the angles it was given."""
    path = os.path.join(str(tmp_path), name)
    angles = np.linspace(0, np.pi, golden["sino_trans"].shape[0]).astype(np.float32)
    mtp.save_cone_preprocessing(path, golden["sino_trans"],
                                {'sinogram_shape': tuple(golden["sino_trans"].shape),
                                 'angles': angles},
                                {'sharpness': 1.0})
    return path, angles


def test_save_load_round_trip(tmp_path, golden):
    path, angles = _write_cone_save(tmp_path, golden)
    with h5py.File(path, 'r') as f:
        assert f.attrs['format'] == 'mbirtorch_preprocessing_v1'
    sino, cone_params, opt_params, weights = mtp.load_cone_preprocessing(path)
    assert np.array_equal(sino, golden["sino_trans"])
    assert cone_params['sinogram_shape'] == tuple(golden["sino_trans"].shape)
    assert np.allclose(cone_params['angles'], angles)
    assert opt_params == {'sharpness': 1.0} and weights is None


def test_load_accepts_older_and_missing_format_tags(tmp_path, golden):
    # Files written before the package was renamed carry the mbirjax tag, and
    # the oldest files and files from other tools have no format attribute at
    # all.  Both must keep loading.
    for tag in ('mbirjax_preprocessing_v1', None):
        path, _ = _write_cone_save(tmp_path, golden, name=f'pp_{tag}.h5')
        with h5py.File(path, 'r+') as f:
            if tag is None:
                del f.attrs['format']
            else:
                f.attrs['format'] = tag
        sino, cone_params, opt_params, weights = mtp.load_cone_preprocessing(path)
        assert np.array_equal(sino, golden["sino_trans"]), tag
        assert cone_params['sinogram_shape'] == tuple(golden["sino_trans"].shape), tag
        assert opt_params == {'sharpness': 1.0} and weights is None, tag
