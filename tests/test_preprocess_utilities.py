def test_downsample_view_data(golden):
    obj, blank, dark, defective = mtp.downsample_view_data(
        golden["obj"].copy(), golden["blank"].copy(), golden["dark"].copy(), (2, 2),
        defective_pixel_array=golden["defective"].copy(), batch_size=5)
    err = _rel_max(obj, golden["ds_obj"])
    print(f"downsample rel_max = {err:.2e}")
    assert err < 1e-5
    assert _rel_max(blank, golden["ds_blank"]) < 1e-6
    assert _rel_max(dark, golden["ds_dark"]) < 1e-6 or golden["ds_dark"].max() == 0
    defective = np.asarray(defective) if len(defective) else np.zeros((0, 2), dtype=np.int64)
    assert np.array_equal(defective, golden["ds_defective"])


