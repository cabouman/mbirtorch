"""Golden parity gates for mbirtorch.preprocess against mbirjax.

Golden data is generated by tests/generate_preprocess_goldens.py IN THE
MBIRJAX ENV and read here (this env never imports jax).  Gates start at 1e-5
rel-max for the deterministic device chains; the measured values are printed
so the floors stay observable.  Host-side numpy/scipy paths (crop, background
offset, beam hardening, helpers) share code with mbirjax and gate tighter.

Functions with a batch_size parameter also get a batch-invariance test (two
batch sizes, same result) -- the cheap guard against seam bugs in the
batching driver.

Comparisons run on CPU (the deterministic-per-process backend).
"""

